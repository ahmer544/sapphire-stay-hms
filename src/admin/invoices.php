<?php
require_once '../config/database.php';
require_once '../config/helpers.php';
requireRole('admin','staff');
$db = getDB();

$generatedBySelect = invoicesSupportGeneratedBy()
  ? 'gu.name AS generated_by_name'
  : 'NULL AS generated_by_name';

$generatedByJoin = invoicesSupportGeneratedBy()
  ? 'LEFT JOIN users gu ON gu.id=i.generated_by'
  : '';

$invoices = $db->query("
    SELECT i.*, b.booking_ref, b.check_in, b.check_out, b.total_amount,
       u.name AS guest_name, u.email, r.name AS room_name,
       $generatedBySelect
    FROM invoices i
    JOIN bookings b ON b.id=i.booking_id
    JOIN users u ON u.id=b.user_id
    JOIN rooms r ON r.id=b.room_id
  $generatedByJoin
    ORDER BY i.issued_at DESC
")->fetchAll();
?>
