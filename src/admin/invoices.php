  <div class="border-b border-[var(--stone)] bg-white px-6 py-4 flex items-center justify-between sticky top-0 z-30">
    <div>
      <h1 class="font-display text-2xl text-[var(--lapis)]">Invoices</h1>
      <p class="text-[var(--text-faint)] text-xs"><?= count($invoices) ?> invoices generated</p>
    </div>
    <?php if (currentRole() === 'admin'): ?>
    <a href="bookings.php" class="text-[var(--gold)] hover:text-[var(--lapis)] text-xs tracking-widest transition uppercase font-semibold">
      Generate: go to Bookings →
    </a>
    <?php endif; ?>
  </div>

  <div class="p-6">
    <div class="bg-white border border-[var(--stone)] rounded-2xl overflow-hidden overflow-x-auto shadow-sm">
      <table class="w-full text-sm min-w-[800px]">
        <thead>
          <tr class="border-b border-[var(--stone)] bg-[var(--bg-alt)]/15">
            <?php foreach (['Invoice #','Booking Ref','Guest','Room','Stay','Amount','Generated By','Issued','Print'] as $h): ?>
            <th class="px-5 py-3 text-left text-[var(--text-faint)] font-medium text-xs tracking-widest uppercase"><?= $h ?></th>
            <?php endforeach; ?>
          </tr>
        </thead>
        <tbody>
          <?php foreach ($invoices as $inv): ?>
          <tr class="border-b border-[var(--stone)]/40 hover:bg-[var(--bg-alt)]/10 transition">
            <td class="px-5 py-4 text-[var(--gold)] font-mono text-xs font-semibold"><?= e($inv['invoice_number']) ?></td>
            <td class="px-5 py-4 text-[var(--lapis)] font-mono text-xs font-semibold"><?= e($inv['booking_ref']) ?></td>
            <td class="px-5 py-4">
              <div class="text-[var(--text)] font-semibold"><?= e($inv['guest_name']) ?></div>
              <div class="text-[var(--text-faint)] text-xs"><?= e($inv['email']) ?></div>
            </td>
            <td class="px-5 py-4 text-[var(--text-muted)] text-xs font-medium"><?= e($inv['room_name']) ?></td>
            <td class="px-5 py-4 text-[var(--text-muted)] text-xs">
              <?= date('d M', strtotime($inv['check_in'])) ?> – <?= date('d M Y', strtotime($inv['check_out'])) ?>
            </td>
            <td class="px-5 py-4 text-[var(--text)] font-bold"><?= currency($inv['total']) ?></td>
            <td class="px-5 py-4 text-[var(--text-faint)] text-xs"><?= e($inv['generated_by_name'] ?? '—') ?></td>
            <td class="px-5 py-4 text-[var(--text-faint)] text-xs"><?= date('d M Y', strtotime($inv['issued_at'])) ?></td>
            <td class="px-5 py-4">
              <a href="<?= adminUrl('invoice-print', ['id' => $inv['id']]) ?>" target="_blank"
                 class="border border-[var(--stone)] text-[var(--text-muted)] hover:border-[var(--lapis)] hover:text-[var(--lapis)] px-3 py-1.5 rounded-lg text-xs transition flex items-center gap-1 w-fit bg-white">
                <i data-lucide="printer" class="w-3.5 h-3.5"></i> Print
              </a>
            </td>
          </tr>
          <?php endforeach; ?>
          <?php if (empty($invoices)): ?>
          <tr><td colspan="9" class="text-center py-10 text-[var(--text-faint)]">
            <?= currentRole() === 'admin'
              ? 'No invoices yet. Go to Bookings and click the invoice icon.'
              : 'No invoices have been generated yet.' ?>
